function [mass, comAboveBall, tiltInertiaCom] = ...
    ballbotPayloadRoverProperties(p, payloadMass)
%BALLBOTPAYLOADROVERPROPERTIES Rover mass/COM/inertia vs mounted payload.
%   [MASS, COMABOVEBALL, TILTINERTIACOM] = BALLBOTPAYLOADROVERPROPERTIES(P,
%   PAYLOADMASS) returns the rover mass properties when the payload-rod
%   solid carries PAYLOADMASS [kg].  Shared by ballbotRev1Parameters and
%   ballbotRobustTorqueGains so the payload-sweep math has one definition.
arguments
    p (1, 1) struct
    payloadMass (1, 1) double
end

wheelCenterAboveBall = p.wheel.geometry.centerFromBall(3, 1);
baseComAboveBall = (p.rover.bodyMass*p.rover.bodyComAboveBall + ...
    3*(p.motor.mass + p.wheel.mass)*wheelCenterAboveBall)/ ...
    p.fullplant.payload.originalRoverMass;
payloadComAboveBall = p.rover.centerAboveBall + ...
    p.fullplant.payload.centerOffset;
mass = p.fullplant.payload.originalRoverMass + payloadMass;
comAboveBall = (p.fullplant.payload.originalRoverMass*baseComAboveBall + ...
    payloadMass*payloadComAboveBall)/mass;
tiltInertiaCom = p.rover.bodyInertia(1) + ...
    p.rover.bodyMass*(p.rover.bodyComAboveBall - comAboveBall)^2 + ...
    3*(p.motor.mass*(3*0.0122^2 + 0.052^2)/12 + ...
       p.motor.mass*(wheelCenterAboveBall - comAboveBall)^2 + ...
       p.wheel.mass*p.wheel.radius^2/2 + ...
       p.wheel.mass*(wheelCenterAboveBall - comAboveBall)^2) + ...
    payloadMass*p.fullplant.payload.length^2/12 + ...
    payloadMass*(payloadComAboveBall - comAboveBall)^2;
end
